-- H8 Social: cooking history
CREATE TABLE recipe_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  recipe_id BIGINT NOT NULL,
  cooking_session_id BIGINT NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_recipe_history_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_recipe_history_recipe FOREIGN KEY (recipe_id) REFERENCES recipes (id) ON DELETE CASCADE,
  CONSTRAINT fk_recipe_history_session FOREIGN KEY (cooking_session_id) REFERENCES cooking_sessions (id) ON DELETE CASCADE,
  CONSTRAINT uk_recipe_history_session UNIQUE (cooking_session_id)
);
CREATE INDEX idx_recipe_history_user_created ON recipe_history (user_id, created_at DESC);
CREATE INDEX idx_recipe_history_recipe ON recipe_history (recipe_id);
